public class PositiveNegativeZero {
    // Check whether a number is positive, negative, or zero.
    public static void main(String args[]) {
        int a = 0;

        if(a > 0) {
            System.out.println("positive");
        }
        else if(a < 0) {
            System.out.println("negative");
        }
        else {
            System.out.println("zero");
        }
    }
}
